/* Build-time tool (host only, never in the image): rasterises the K1 GUI fonts with FreeType into a
 * C file with 8-bit coverage bitmaps (src/grafika/k1_czcionka.h, ADR 0009).
 *   czcionki KATALOG_Z_CZCIONKAMI > k1_czcionki_dane.c
 * Deterministic: same FreeType and font files → same output. */
#include <ft2build.h>
#include FT_FREETYPE_H
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

struct styl {
    const char *plik;
    int px;
    int tylko_cyfry;
};

static const struct styl style[] = {
    { "IBMPlexSans-Regular.ttf", 13, 0 }, { "IBMPlexSans-Medium.ttf", 13, 0 }, { "IBMPlexSans-Regular.ttf", 15, 0 },
    { "IBMPlexSans-Medium.ttf", 15, 0 },  { "IBMPlexSerif-Regular.ttf", 24, 0 }, { "IBMPlexSerif-Light.ttf", 64, 1 },
};

/* ASCII, Polish letters and a few typographic signs used by the interface. */
static const unsigned dodatkowe[] = { 0x104, 0x105, 0x106, 0x107, 0x118, 0x119, 0x141, 0x142, 0x143, 0x144, 0xd3, 0xf3,
                                      0x15a, 0x15b, 0x179, 0x17a, 0x17b, 0x17c, 0xb0, 0xb7, 0xd7, 0x2013, 0x2014, 0x2026,
                                      0x201e, 0x201d, 0x2022, 0x2190, 0x2192 };

static int por(const void *a, const void *b)
{
    unsigned x = *(const unsigned *)a, y = *(const unsigned *)b;
    return x < y ? -1 : x > y;
}

int main(int argc, char **argv)
{
    FT_Library ft;
    size_t s;
    unsigned long razem = 0;
    if (argc != 2 || FT_Init_FreeType(&ft) != 0)
        return 1;
    printf("/* Generated by narzedzia/czcionki.c from IBM Plex (OFL-1.1) — do not edit. */\n");
    printf("#include \"k1_czcionka.h\"\n\n");
    for (s = 0; s < sizeof style / sizeof style[0]; s++) {
        char sciezka[512];
        FT_Face f;
        unsigned kody[256], n = 0, i;
        unsigned long offset = 0;
        snprintf(sciezka, sizeof sciezka, "%s/%s", argv[1], style[s].plik);
        if (FT_New_Face(ft, sciezka, 0, &f) != 0 || FT_Set_Pixel_Sizes(f, 0, (FT_UInt)style[s].px) != 0) {
            fprintf(stderr, "czcionki: nie można wczytać %s\n", sciezka);
            return 1;
        }
        if (style[s].tylko_cyfry) {
            for (i = '0'; i <= '9'; i++)
                kody[n++] = i;
            kody[n++] = ':';
            kody[n++] = ' ';
        } else {
            for (i = 0x20; i < 0x7f; i++)
                kody[n++] = i;
            for (i = 0; i < sizeof dodatkowe / sizeof dodatkowe[0]; i++)
                kody[n++] = dodatkowe[i];
        }
        qsort(kody, n, sizeof kody[0], por);
        printf("static const uint8_t px%zu[] = {", s);
        for (i = 0; i < n; i++) {
            unsigned x, y;
            if (FT_Load_Char(f, kody[i], FT_LOAD_RENDER | FT_LOAD_TARGET_LIGHT) != 0)
                return 1;
            for (y = 0; y < f->glyph->bitmap.rows; y++)
                for (x = 0; x < f->glyph->bitmap.width; x++, offset++)
                    printf("%s%u,", offset % 32 == 0 ? "\n" : "", f->glyph->bitmap.buffer[y * (unsigned)f->glyph->bitmap.pitch + x]);
        }
        printf("\n0 };\n");
        printf("static const struct k1_glif gl%zu[] = {\n", s);
        offset = 0;
        for (i = 0; i < n; i++) {
            FT_Load_Char(f, kody[i], FT_LOAD_RENDER | FT_LOAD_TARGET_LIGHT);
            printf("  { 0x%x, %d, %d, %u, %u, %ld, %lu },\n", kody[i], f->glyph->bitmap_left, f->glyph->bitmap_top,
                   f->glyph->bitmap.width, f->glyph->bitmap.rows, (long)f->glyph->advance.x, offset);
            offset += (unsigned long)f->glyph->bitmap.width * f->glyph->bitmap.rows;
        }
        printf("};\n\n");
        razem += offset;
        printf("#define CZ%zu { gl%zu, %u, %ld, %ld, %ld, px%zu }\n", s, s, n, (long)(f->size->metrics.ascender >> 6),
               (long)(f->size->metrics.descender >> 6), (long)(f->size->metrics.height >> 6), s);
        FT_Done_Face(f);
    }
    printf("const struct k1_czcionka k1_czcionki[K1_CZ_LICZBA] = { CZ0, CZ1, CZ2, CZ3, CZ4, CZ5 };\n");
    fprintf(stderr, "czcionki: %zu stylów, %lu bajtów bitmap\n", sizeof style / sizeof style[0], razem);
    FT_Done_FreeType(ft);
    return 0;
}
