/* K1 — signing of system images at build time (M6a, ADR 0021). Runs on the build host.
 *
 *   podpisz klucz-publiczny          > k1_klucz.h     the public key for the programs of K1
 *   podpisz obraz PLIK WERSJA                         manifest into the K1-EFI image PLIK
 *
 * The key: environment variable K1_KLUCZ_PODPISU = 32 random bytes in base64 (the GitHub Actions
 * secret of the same name; never in the repository). Without it the build is a developer build:
 * the header says K1_KLUCZ_JEST 0 and the manifest is unsigned. EdDSA (Monocypher) is
 * deterministic: the same inputs give the same bytes. */
#include <fcntl.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

#include "k1_manifest.h"
#include "monocypher.h"

static int b64(int c)
{
    if (c >= 'A' && c <= 'Z')
        return c - 'A';
    if (c >= 'a' && c <= 'z')
        return c - 'a' + 26;
    if (c >= '0' && c <= '9')
        return c - '0' + 52;
    if (c == '+' || c == '-')
        return 62;
    if (c == '/' || c == '_')
        return 63;
    return -1;
}

/* The seed from the environment: 1 = there, 0 = none (developer build). Exits on a malformed one. */
static int ziarno(uint8_t out[32])
{
    const char *s = getenv("K1_KLUCZ_PODPISU");
    uint32_t akumulator = 0;
    int bity = 0, n = 0;
    if (s == NULL || *s == '\0')
        return 0;
    for (; *s != '\0'; s++) {
        int v;
        if (*s == '=' || *s == '\n' || *s == '\r' || *s == ' ')
            continue;
        v = b64((unsigned char)*s);
        if (v < 0) {
            fprintf(stderr, "podpisz: K1_KLUCZ_PODPISU nie jest base64\n");
            exit(2);
        }
        akumulator = akumulator << 6 | (uint32_t)v;
        bity += 6;
        if (bity >= 8) {
            bity -= 8;
            if (n >= 32) {
                fprintf(stderr, "podpisz: K1_KLUCZ_PODPISU ma więcej niż 32 bajty\n");
                exit(2);
            }
            out[n++] = (uint8_t)(akumulator >> bity);
        }
    }
    if (n != 32) {
        fprintf(stderr, "podpisz: K1_KLUCZ_PODPISU musi mieć dokładnie 32 bajty (ma %d)\n", n);
        exit(2);
    }
    return 1;
}

static int klucze(uint8_t tajny[64], uint8_t publiczny[32])
{
    uint8_t z[32];
    if (!ziarno(z))
        return 0;
    crypto_eddsa_key_pair(tajny, publiczny, z); /* wipes z */
    return 1;
}

static int klucz_publiczny(void)
{
    uint8_t tajny[64], pub[32], id[8];
    int i, jest = klucze(tajny, pub);
    crypto_wipe(tajny, sizeof tajny);
    printf("/* Generated by narzedzia/podpisz.c — the public key that signs K1 releases (ADR 0021). */\n");
    if (!jest) {
        printf("#define K1_KLUCZ_JEST 0 /* developer build: no K1_KLUCZ_PODPISU */\n");
        printf("static const unsigned char k1_klucz_publiczny[32] = { 0 };\n");
        return 0;
    }
    k1_klucz_id(pub, id);
    printf("#define K1_KLUCZ_JEST 1\n#define K1_KLUCZ_ID \"");
    for (i = 0; i < 8; i++)
        printf("%02x", id[i]);
    printf("\"\nstatic const unsigned char k1_klucz_publiczny[32] = {");
    for (i = 0; i < 32; i++)
        printf("%s0x%02x", i ? ", " : " ", pub[i]);
    printf(" };\n");
    return 0;
}

static int obraz(const char *plik, const char *wersja)
{
    static uint8_t buf[1u << 20];
    uint8_t tajny[64], pub[32], man[K1_MANIFEST_BAJTY];
    crypto_blake2b_ctx ctx;
    struct k1_manifest m;
    int32_t w = k1_wersja_z_tekstu(wersja);
    uint64_t off;
    int fd = open(plik, O_RDWR), jest;
    if (fd < 0 || w < 0 || strlen(wersja) >= sizeof m.tekst) {
        fprintf(stderr, "podpisz: %s / wersja %s\n", plik, wersja);
        return 1;
    }
    if (lseek(fd, 0, SEEK_END) < (off_t)(K1_MANIFEST_OFF + K1_MANIFEST_BAJTY)) {
        fprintf(stderr, "podpisz: obraz za mały na manifest\n");
        return 1;
    }
    crypto_blake2b_init(&ctx, 32);
    for (off = 0; off < K1_MANIFEST_OFF; off += sizeof buf) {
        if (pread(fd, buf, sizeof buf, (off_t)off) != (ssize_t)sizeof buf)
            return 1;
        crypto_blake2b_update(&ctx, buf, sizeof buf);
    }
    memset(&m, 0, sizeof m);
    crypto_blake2b_final(&ctx, m.skrot);
    m.wersja = (uint32_t)w;
    m.fat_bajty = K1_MANIFEST_OFF;
    snprintf(m.tekst, sizeof m.tekst, "%s", wersja);
    jest = klucze(tajny, pub);
    k1_manifest_zbuduj(&m, jest ? tajny : NULL, pub, man);
    crypto_wipe(tajny, sizeof tajny);
    if (pwrite(fd, man, sizeof man, K1_MANIFEST_OFF) != (ssize_t)sizeof man || close(fd) != 0)
        return 1;
    if (jest && k1_manifest_sprawdz_podpis(man, pub) != 0) {
        fprintf(stderr, "podpisz: podpis nie przechodzi własnego sprawdzenia\n");
        return 1;
    }
    printf("%s: manifest %s, %s\n", plik, wersja, jest ? "podpisany" : "BEZ podpisu (wersja deweloperska)");
    return 0;
}

int main(int argc, char **argv)
{
    if (argc == 2 && strcmp(argv[1], "klucz-publiczny") == 0)
        return klucz_publiczny();
    if (argc == 4 && strcmp(argv[1], "obraz") == 0)
        return obraz(argv[2], argv[3]);
    fprintf(stderr, "użycie: podpisz klucz-publiczny | podpisz obraz PLIK WERSJA\n");
    return 2;
}
