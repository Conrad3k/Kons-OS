/* K1 — signing of system images at build time (M6a, ADR 0021). Runs on the build host.
 *
 *   podpisz klucz-publiczny          > k1_klucz.h     the public key for the programs of K1
 *   podpisz slot PLIK WERSJA WYDANIE FAT_BAJTY        slot manifest (format 2, ADR 0022) into the slot file PLIK
 *   podpisz grubenv PLIK                              GRUB's environment block for a fresh K1-EFI (slot a)
 *   podpisz uklad PLIK GRUBENV_OFF A_OFF B_OFF SLOT_BAJTY  the layout block into the K1-EFI image PLIK (checked; the
 *                                                     slots' size since 0.10.9 step 4b — 768 MiB, 128 MiB before)
 *   podpisz start PLIK                                the manifest of the boot files (format 3, ADR 0038) of the
 *                                                     K1-EFI image PLIK into its slot A, beside the slot manifest
 *
 * The key: environment variable K1_KLUCZ_PODPISU = 32 random bytes in base64 (the GitHub Actions
 * secret of the same name; never in the repository). Without it the build is a developer build:
 * the header says K1_KLUCZ_JEST 0 and the manifest is unsigned. EdDSA (Monocypher) is
 * deterministic: the same inputs give the same bytes. */
#include <fcntl.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

#include "k1_fat32.h"
#include "klucz.h"
#include "k1_manifest.h"
#include "k1_uklad.h"
#include "monocypher.h"

static int klucz_publiczny(void)
{
    uint8_t tajny[64], pub[32], id[8];
    int i, jest = klucze(tajny, pub);
    crypto_wipe(tajny, sizeof tajny);
    printf("/* Generated by narzedzia/podpisz.c — the public key that signs K1 releases (ADR 0021). */\n");
    if (!jest) {
        printf("#define K1_KLUCZ_JEST 0 /* developer build: no K1_KLUCZ_PODPISU */\n");
        printf("static const unsigned char k1_klucz_publiczny[32] = { 0 };\n");
        return 0;
    }
    k1_klucz_id(pub, id);
    printf("#define K1_KLUCZ_JEST 1\n#define K1_KLUCZ_ID \"");
    for (i = 0; i < 8; i++)
        printf("%02x", id[i]);
    printf("\"\nstatic const unsigned char k1_klucz_publiczny[32] = {");
    for (i = 0; i < 32; i++)
        printf("%s0x%02x", i ? ", " : " ", pub[i]);
    printf(" };\n");
    return 0;
}

/* 32 hex digits → 16 bytes; -1 if not exactly that. */
static int hex16(const char *t, uint8_t out[16])
{
    int i;
    if (strlen(t) != 32)
        return -1;
    for (i = 0; i < 32; i++) {
        int c = t[i], v = c >= '0' && c <= '9' ? c - '0' : c >= 'a' && c <= 'f' ? c - 'a' + 10 : -1;
        if (v < 0)
            return -1;
        out[i / 2] = (uint8_t)(i % 2 ? out[i / 2] | v : v << 4);
    }
    return 0;
}

/* BLAKE2b-256 of the first n bytes of fd */
static int skrot(int fd, uint64_t n, uint8_t out[32])
{
    static uint8_t buf[1u << 20];
    crypto_blake2b_ctx ctx;
    uint64_t off;
    crypto_blake2b_init(&ctx, 32);
    for (off = 0; off < n; off += sizeof buf) {
        size_t ile = n - off < sizeof buf ? (size_t)(n - off) : sizeof buf;
        if (pread(fd, buf, ile, (off_t)off) != (ssize_t)ile)
            return -1;
        crypto_blake2b_update(&ctx, buf, ile);
    }
    crypto_blake2b_final(&ctx, out);
    return 0;
}

static int slot(const char *plik, const char *wersja, const char *wydanie, const char *fat)
{
    uint8_t tajny[64], pub[32], man[K1_MANIFEST_BAJTY];
    struct k1_manifest m, r;
    int32_t w = k1_wersja_z_tekstu(wersja);
    unsigned long long fat_bajty = strtoull(fat, NULL, 10);
    int fd = open(plik, O_RDWR), jest;
    off_t rozm = fd < 0 ? -1 : lseek(fd, 0, SEEK_END); /* the slot's size (0.10.9 step 4b: not fixed any more) */
    memset(&m, 0, sizeof m);
    if (fd < 0 || w < 0 || strlen(wersja) >= sizeof m.tekst || hex16(wydanie, m.wydanie) != 0 || fat_bajty == 0 ||
        rozm < (off_t)K1_SLOT_MIN || rozm > (off_t)K1_SLOT_MAKS || (uint64_t)rozm % K1_SLOT_MIB != 0 ||
        fat_bajty > k1_slot_man_off((uint64_t)rozm)) {
        fprintf(stderr, "podpisz slot: %s / wersja %s / wydanie %s / %s B\n", plik, wersja, wydanie, fat);
        return 1;
    }
    m.format = K1_MANIFEST_SLOT;
    m.wersja = (uint32_t)w;
    m.fat_bajty = fat_bajty;
    snprintf(m.tekst, sizeof m.tekst, "%s", wersja);
    if (skrot(fd, fat_bajty, m.skrot) != 0)
        return 1;
    jest = klucze(tajny, pub);
    k1_manifest_zbuduj(&m, jest ? tajny : NULL, pub, man);
    crypto_wipe(tajny, sizeof tajny);
    if (pwrite(fd, man, sizeof man, (off_t)k1_slot_man_off((uint64_t)rozm)) != (ssize_t)sizeof man || close(fd) != 0 ||
        k1_manifest_czytaj(man, &r) != 0 || (jest && k1_manifest_sprawdz_podpis(man, pub) != 0))
        return 1;
    printf("%s: manifest slotu %s (%llu MiB), %s\n", plik, wersja, fat_bajty >> 20, jest ? "podpisany" : "BEZ podpisu");
    return 0;
}

static int grubenv(const char *plik)
{
    uint8_t e[K1_GRUBENV_BAJTY];
    struct k1_grubenv g = { 'a', 0, 'a', 0 };
    FILE *f = fopen(plik, "wb");
    k1_grubenv_zbuduj(&g, e);
    if (f == NULL || fwrite(e, 1, sizeof e, f) != sizeof e || fclose(f) != 0)
        return 1;
    return 0;
}

static int uklad(const char *plik, const char *genv, const char *a, const char *b, const char *slot)
{
    uint8_t blok[K1_UKLAD_BAJTY], stary[K1_UKLAD_BAJTY], e[K1_GRUBENV_BAJTY], man[K1_MANIFEST_BAJTY];
    struct k1_uklad u, r;
    struct k1_grubenv g;
    struct k1_manifest m;
    int fd = open(plik, O_RDWR);
    off_t rozm = fd < 0 ? -1 : lseek(fd, 0, SEEK_END);
    size_t i;
    u.fat_bajty = (uint64_t)rozm;
    u.grubenv_off = strtoull(genv, NULL, 10);
    u.slot_bajty = strtoull(slot, NULL, 10);
    u.slot_off[0] = strtoull(a, NULL, 10);
    u.slot_off[1] = strtoull(b, NULL, 10);
    k1_uklad_zbuduj(&u, blok);
    if (rozm <= 0 || k1_uklad_czytaj(blok, (uint64_t)rozm, &r) != 0) {
        fprintf(stderr, "podpisz uklad: niepoprawny układ (grubenv %s, a %s, b %s, miejsca %s B)\n", genv, a, b, slot);
        return 1;
    }
    /* the place must be unused (FAT32: sector 2 of the reserved area), grubenv and slot A where we say */
    if (pread(fd, stary, sizeof stary, K1_UKLAD_OFF) != (ssize_t)sizeof stary ||
        pread(fd, e, sizeof e, (off_t)u.grubenv_off) != (ssize_t)sizeof e ||
        pread(fd, man, sizeof man, (off_t)(u.slot_off[0] + k1_slot_man_off(u.slot_bajty))) != (ssize_t)sizeof man)
        return 1;
    for (i = 0; i < sizeof stary; i++)
        if (stary[i] != 0) {
            fprintf(stderr, "podpisz uklad: miejsce na blok układu jest zajęte\n");
            return 1;
        }
    if (k1_grubenv_czytaj(e, &g) != 0 || g.slot != 'a' || k1_manifest_czytaj(man, &m) != 0 || m.format != K1_MANIFEST_SLOT) {
        fprintf(stderr, "podpisz uklad: pod podanymi przesunięciami nie ma grubenv / manifestu slotu A\n");
        return 1;
    }
    if (pwrite(fd, blok, sizeof blok, K1_UKLAD_OFF) != (ssize_t)sizeof blok || close(fd) != 0)
        return 1;
    printf("%s: układ — grubenv %llu, slot A %llu MiB, slot B %llu MiB, po %llu MiB (system %s)\n", plik,
           (unsigned long long)u.grubenv_off, (unsigned long long)(u.slot_off[0] >> 20),
           (unsigned long long)(u.slot_off[1] >> 20), (unsigned long long)(u.slot_bajty >> 20), m.tekst);
    return 0;
}

static int czytaj_fd(void *ctx, uint64_t od, void *buf, uint32_t n)
{
    return pread(*(int *)ctx, buf, n, (off_t)od) == (ssize_t)n ? 0 : -1;
}

/* The digest of the boot files of the K1-EFI image (everything but grubenv and the slots), signed as a format-3
 * manifest of the same release as slot A's, written right after slot A's manifest. */
static int start(const char *plik)
{
    static struct k1_fat32 f;
    static struct k1_fat32_drzewo d;
    static uint8_t zajete[K1_FAT32_MAPA];
    uint8_t blok[K1_UKLAD_BAJTY], man[K1_MANIFEST_BAJTY], tajny[64], pub[32];
    struct k1_uklad u;
    struct k1_manifest a, m, r;
    struct k1_fat32_we we;
    uint64_t bez[3];
    int fd = open(plik, O_RDWR), jest;
    off_t rozm = fd < 0 ? -1 : lseek(fd, 0, SEEK_END);
    if (rozm <= 0 || pread(fd, blok, sizeof blok, K1_UKLAD_OFF) != (ssize_t)sizeof blok ||
        k1_uklad_czytaj(blok, (uint64_t)rozm, &u) != 0 ||
        pread(fd, man, sizeof man, (off_t)(u.slot_off[0] + k1_slot_man_off(u.slot_bajty))) != (ssize_t)sizeof man ||
        k1_manifest_czytaj(man, &a) != 0 || a.format != K1_MANIFEST_SLOT) {
        fprintf(stderr, "podpisz start: %s bez bloku układu albo manifestu miejsca A\n", plik);
        return 1;
    }
    we.czytaj = czytaj_fd;
    we.ctx = &fd;
    we.rozmiar = (uint64_t)rozm;
    bez[0] = u.grubenv_off;
    bez[1] = u.slot_off[0];
    bez[2] = u.slot_off[1];
    memset(&m, 0, sizeof m);
    if (k1_fat32_otworz(&f, &we) != 0 || k1_fat32_drzewo(&f, &d, zajete) != 0 || k1_fat32_skrot(&f, &d, bez, 3, m.skrot) != 0) {
        fprintf(stderr, "podpisz start: %s — FAT32 nieczytelny albo bez grubenv i miejsc A/B w jednym kawałku\n", plik);
        return 1;
    }
    m.format = K1_MANIFEST_START;
    m.wersja = a.wersja;
    m.fat_bajty = u.fat_bajty;
    memcpy(m.tekst, a.tekst, sizeof m.tekst);
    memcpy(m.wydanie, a.wydanie, sizeof m.wydanie);
    jest = klucze(tajny, pub);
    k1_manifest_zbuduj(&m, jest ? tajny : NULL, pub, man);
    crypto_wipe(tajny, sizeof tajny);
    if (pwrite(fd, man, sizeof man, (off_t)(u.slot_off[0] + k1_slot_start_off(u.slot_bajty))) != (ssize_t)sizeof man || close(fd) != 0 ||
        k1_manifest_czytaj(man, &r) != 0 || (jest && k1_manifest_sprawdz_podpis(man, pub) != 0))
        return 1;
    printf("%s: manifest plików startowych %s (%d plików i folderów), %s\n", plik, m.tekst, d.n,
           jest ? "podpisany" : "BEZ podpisu");
    return 0;
}

int main(int argc, char **argv)
{
    if (argc == 2 && strcmp(argv[1], "klucz-publiczny") == 0)
        return klucz_publiczny();
    if (argc == 3 && strcmp(argv[1], "start") == 0)
        return start(argv[2]);
    if (argc == 6 && strcmp(argv[1], "slot") == 0)
        return slot(argv[2], argv[3], argv[4], argv[5]);
    if (argc == 3 && strcmp(argv[1], "grubenv") == 0)
        return grubenv(argv[2]);
    if (argc == 7 && strcmp(argv[1], "uklad") == 0)
        return uklad(argv[2], argv[3], argv[4], argv[5], argv[6]);
    fprintf(stderr, "użycie: podpisz klucz-publiczny | slot PLIK WERSJA WYDANIE FAT_BAJTY | "
                    "grubenv PLIK | uklad PLIK GRUBENV_OFF A_OFF B_OFF | start PLIK\n");
    return 2;
}
