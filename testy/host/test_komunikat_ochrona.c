/* K1 — host test of the service protocol: OCHRONA — the TPM (0.13.0 step 2, ADR 0057), the rescue mode (step 3, ADR
 * 0058), the input devices from USB that wait for the owner (step 5, ADR 0060); src/wspolne/k1_kom_nadzorca.c. Part of
 * test_komunikat (test_komunikat.h). */
#define K1_TEST_CZESC
#include "test_komunikat.h"
#include "k1_tpm.h"
#include "k1_urz_wejscia.h"

void ochrona(void)
{
    /* 0.13.0 step 2 (ADR 0057): OCHRONA — the state out, "To moje dane" and a test's generation in */
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_STAN, K1_TPM_20, K1_OCHR_FL_STARSZA | K1_OCHR_FL_COFNIETE, 2, 0), K1_KIER_OD_NADZORCY));
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_STAN, K1_TPM_BRAK, 0, 0, 0), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_STAN, K1_TPM_ZAJETY + 1, 0, 0, 0), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_STAN, K1_TPM_20, K1_OCHR_FL_MAKS + 1, 0, 0), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_STAN, K1_TPM_20, 0, K1_GEN_MAKS + 1, 0), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_STAN, K1_TPM_20, 0, 1, 0), K1_KIER_DO_NADZORCY)); /* the state only out */
    EXPECT(zle(K(K1_KOM_OCHRONA, 1, K1_OCHR_STAN, K1_TPM_20, 0, 1, 0), K1_KIER_OD_NADZORCY));
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_MOJE_DANE, 0, 0, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_MOJE_DANE, 1, 0, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_MOJE_DANE, 0, 0, 0, 0), K1_KIER_OD_NADZORCY));
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_TEST, 2, 0, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_TEST, 0, 0, 0, 0), K1_KIER_DO_NADZORCY)); /* never generation 0 */
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_TEST, K1_GEN_MAKS + 1, 0, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, 0, 0, 0, 0, 0), K1_KIER_DO_NADZORCY));
    /* 0.13.0 step 3 (ADR 0058): the rescue mode — its state out, the rescue screen's requests in */
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_RATUNEK, 0x000d01, 0x000d00, K1_RAP_ZAPISANY, 9), K1_KIER_OD_NADZORCY));
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_RATUNEK, 0x000d01, 0, K1_RAP_BLAD, K1_INST_BLAD_FAT), K1_KIER_OD_NADZORCY));
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_RATUNEK, 0, 0, K1_RAP_NIC, 0), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_RATUNEK, 0, 0, K1_RAP_ZAPISANY, 10), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_RATUNEK, 0, 0, K1_RAP_BLAD, 0), K1_KIER_OD_NADZORCY)); /* an error needs its code */
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_RATUNEK, 0, 0, K1_RAP_NIC, 1), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_RATUNEK, 0, 0, K1_RAP_MAKS + 1, 0), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_RATUNEK, K1_INST_WERSJA, 0, 0, 0), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_RATUNEK, 0, 0, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_NORMALNIE, 0, 0, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_POPRZEDNIA, 0, 0, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_RAPORT, 0, 0, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_RAPORT, 1, 0, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_RAPORT + 1, 0, 0, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_NORMALNIE, 0, 0, 0, 0), K1_KIER_OD_NADZORCY));
    /* 0.13.0 step 5 (ADR 0060): the question about USB devices out, the owner's answer in */
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB, K1_URZ_KLAWIATURA, 1, 1, 0), K1_KIER_OD_NADZORCY));
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB, K1_URZ_MAKS, 32, K1_OCHR_PYTANIE_MAKS, 0), K1_KIER_OD_NADZORCY));
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB, 0, 0, 7, 0), K1_KIER_OD_NADZORCY)); /* nothing waits any more */
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB, K1_URZ_MYSZ, 0, 7, 0), K1_KIER_OD_NADZORCY)); /* c = 0: b = 0 */
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB, 0, 1, 7, 0), K1_KIER_OD_NADZORCY)); /* something waits: what */
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB, K1_URZ_MAKS + 1, 1, 7, 0), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB, K1_URZ_MYSZ, 33, 7, 0), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB, K1_URZ_MYSZ, 1, -1, 0), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB, K1_URZ_MYSZ, 1, K1_OCHR_PYTANIE_MAKS + 1, 0), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB, K1_URZ_MYSZ, 1, 7, 1), K1_KIER_OD_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB, K1_URZ_MYSZ, 1, 7, 0), K1_KIER_DO_NADZORCY)); /* the question only out */
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB_ZGODA, 1, 7, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(ok(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB_ZGODA, 0, K1_OCHR_PYTANIE_MAKS, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB_ZGODA, 2, 7, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB_ZGODA, 1, -1, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB_ZGODA, 1, 7, 1, 0), K1_KIER_DO_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB_ZGODA, 1, 7, 0, 0), K1_KIER_OD_NADZORCY)); /* the answer only in */
    EXPECT(zle(K(K1_KOM_OCHRONA, 1, K1_OCHR_USB_ZGODA, 1, 7, 0, 0), K1_KIER_DO_NADZORCY));
    EXPECT(zle(K(K1_KOM_OCHRONA, 0, K1_OCHR_USB_ZGODA + 1, 0, 0, 0, 0), K1_KIER_DO_NADZORCY));
}
