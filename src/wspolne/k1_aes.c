static uint8_t xt(uint8_t x) /* multiplication by 2 in GF(2^8) */
{
    return (uint8_t)(x << 1 ^ (x & 0x80 ? 0x1b : 0));
}

static uint8_t mn(uint8_t x, uint8_t y) /* multiplication in GF(2^8) */
{
    uint8_t r = 0;
    while (y) {
        if (y & 1)
            r ^= x;
        x = xt(x);
        y >>= 1;
    }
    return r;
}

void k1_aes_klucz(struct k1_aes *a, const uint8_t klucz[16])
{
    uint8_t rc = 1;
    int i;
    memcpy(a->rk, klucz, 16);
    for (i = 16; i < 176; i += 4) {
        uint8_t t[4];
        memcpy(t, a->rk + i - 4, 4);
        if (i % 16 == 0) { /* RotWord, SubWord, Rcon */
            uint8_t u = t[0];
            t[0] = (uint8_t)(SBOX[t[1]] ^ rc);
            t[1] = SBOX[t[2]];
            t[2] = SBOX[t[3]];
            t[3] = SBOX[u];
            rc = xt(rc);
        }
        a->rk[i] = a->rk[i - 16] ^ t[0];
        a->rk[i + 1] = a->rk[i - 15] ^ t[1];
        a->rk[i + 2] = a->rk[i - 14] ^ t[2];
        a->rk[i + 3] = a->rk[i - 13] ^ t[3];
    }
}

static void dodaj_klucz(uint8_t s[16], const uint8_t *k)
{
    int i;
    for (i = 0; i < 16; i++)
        s[i] ^= k[i];
}

/* The state is column by column (s[4c + r]); ShiftRows moves row r left by r (dir 1) or right (dir -1). */
static void przesun(uint8_t s[16], int dir)
{
    uint8_t t[16];
    int r, c;
    for (r = 0; r < 4; r++)
        for (c = 0; c < 4; c++)
            t[4 * c + r] = s[4 * ((c + dir * r + 4) % 4) + r];
    memcpy(s, t, 16);
}

static void mieszaj(uint8_t s[16], const uint8_t m[4])
{
    int c;
    for (c = 0; c < 4; c++) {
        uint8_t a0 = s[4 * c], a1 = s[4 * c + 1], a2 = s[4 * c + 2], a3 = s[4 * c + 3];
        s[4 * c] = (uint8_t)(mn(a0, m[0]) ^ mn(a1, m[1]) ^ mn(a2, m[2]) ^ mn(a3, m[3]));
        s[4 * c + 1] = (uint8_t)(mn(a0, m[3]) ^ mn(a1, m[0]) ^ mn(a2, m[1]) ^ mn(a3, m[2]));
        s[4 * c + 2] = (uint8_t)(mn(a0, m[2]) ^ mn(a1, m[3]) ^ mn(a2, m[0]) ^ mn(a3, m[1]));
        s[4 * c + 3] = (uint8_t)(mn(a0, m[1]) ^ mn(a1, m[2]) ^ mn(a2, m[3]) ^ mn(a3, m[0]));
    }
}

void k1_aes_szyfruj(const struct k1_aes *a, const uint8_t we[16], uint8_t wy[16])
{
    static const uint8_t m[4] = { 2, 3, 1, 1 };
    uint8_t s[16];
    int r, i;
    memcpy(s, we, 16);
    dodaj_klucz(s, a->rk);
    for (r = 1; r <= 10; r++) {
        for (i = 0; i < 16; i++)
            s[i] = SBOX[s[i]];
        przesun(s, 1);
        if (r < 10)
            mieszaj(s, m);
        dodaj_klucz(s, a->rk + 16 * r);
    }
    memcpy(wy, s, 16);
    k1_wymaz(s, sizeof s);
}

void k1_aes_odszyfruj(const struct k1_aes *a, const uint8_t we[16], uint8_t wy[16])
{
    static const uint8_t m[4] = { 14, 11, 13, 9 };
    uint8_t s[16];
    int r, i;
    memcpy(s, we, 16);
    dodaj_klucz(s, a->rk + 160);
    for (r = 9; r >= 0; r--) {
        przesun(s, -1);
        for (i = 0; i < 16; i++)
            s[i] = SBOX_ODWR[s[i]];
        dodaj_klucz(s, a->rk + 16 * r);
        if (r > 0)
            mieszaj(s, m);
    }
    memcpy(wy, s, 16);
    k1_wymaz(s, sizeof s);
}

void k1_aes_zawin(const uint8_t kek[16], const uint8_t *dane, size_t n, uint8_t *wynik)
{
    struct k1_aes a;
    uint8_t b[16];
    size_t ile = n / 8, i, j;
    k1_aes_klucz(&a, kek);
    memset(b, 0xa6, 8);
    memmove(wynik + 8, dane, n);
    for (j = 0; j <= 5; j++)
        for (i = 1; i <= ile; i++) {
            uint64_t t = (uint64_t)(ile * j + i);
            int k;
            memcpy(b + 8, wynik + 8 * i, 8);
            k1_aes_szyfruj(&a, b, b);
            for (k = 0; k < 8; k++)
                b[7 - k] ^= (uint8_t)(t >> (8 * k));
            memcpy(wynik + 8 * i, b + 8, 8);
        }
    memcpy(wynik, b, 8);
    k1_wymaz(&a, sizeof a);
    k1_wymaz(b, sizeof b);
}

int k1_aes_rozwin(const uint8_t kek[16], const uint8_t *dane, size_t n, uint8_t *wynik)
{
    struct k1_aes a;
    uint8_t b[16], roznica = 0;
    size_t ile, i, j;
    int k;
    if (n < 24 || n % 8 != 0)
        return -1;
    ile = n / 8 - 1;
    k1_aes_klucz(&a, kek);
    memcpy(b, dane, 8);
    memmove(wynik, dane + 8, n - 8);
    for (j = 6; j-- > 0;)
        for (i = ile; i >= 1; i--) {
            uint64_t t = (uint64_t)(ile * j + i);
            for (k = 0; k < 8; k++)
                b[7 - k] ^= (uint8_t)(t >> (8 * k));
            memcpy(b + 8, wynik + 8 * (i - 1), 8);
            k1_aes_odszyfruj(&a, b, b);
            memcpy(wynik + 8 * (i - 1), b + 8, 8);
        }
    for (k = 0; k < 8; k++)
        roznica |= (uint8_t)(b[k] ^ 0xa6);
    k1_wymaz(&a, sizeof a);
    k1_wymaz(b, sizeof b);
    if (roznica != 0) {
        k1_wymaz(wynik, n - 8);
        return -1;
    }
    return 0;
}
